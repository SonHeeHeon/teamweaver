ROLES = {"특급": "기술 리더", "고급": "파트 리더", "중급": "핵심 담당자", "초급": "담당자"}


def positive_text(rng: random.Random, items: list[str], *, work_name: str, domain: str, skill: str,
                  area: str, grade: str) -> str:
    """~4-5 sentences: an opener with the work context, one sentence per picked strength (at most four)."""
    fill = {"name": work_name, "domain": domain, "skill": skill, "area": area, "role": ROLES.get(grade, "담당자")}
    parts = [rng.choice(OPENERS).format(**fill)]
    for it in items[:4]:
        parts.append(rng.choice(POSITIVE[it]).format(**fill))
    if len(items) > 4:
        parts.append(f"그 밖에도 {', '.join(items[4:])} 측면에서 좋은 모습을 보였습니다.")
    return " ".join(parts)


def negative_text(rng: random.Random, items: list[str], *, skill: str) -> str:
    """~1-2 sentences: the first weakness in full, the rest named briefly."""
    first = NEGATIVE[items[0]].format(skill=skill)
    if len(items) == 1:
        return first
    return first + f" 또한 {', '.join(items[1:])} 측면도 보완하면 더 좋겠습니다."
