def _topic(word: str) -> str:
    """은/는: 마지막 글자 받침 유무."""
    code = ord(word[-1]) - 0xAC00
    return word + ("은" if 0 <= code < 11172 and code % 28 else "는")


def org_review_prose(prng: random.Random, style: str, pos_items: list[str], neg_items: list[str], positive: str,
                     *, skill: str) -> tuple[str, str]:
    """조직형 묶음 리뷰 한 건의 (칭찬 글, 아쉬운 점 글). positive는 positive_text가 이미 쓴 글(항목 난수열을 그대로 쓰려고 밖에서 만든다).
    style: normal(아쉬운 점 항목마다 한 문장) · blunt(직설형 평가자: 칭찬은 한 줄, 아쉬운 점은 항목마다 직설 문장) ·
    harsh(항목과 어긋남 — 항목보다 글이 독함) · soft(항목과 어긋남 — 항목보다 글이 부드러움)."""
    if style == "normal":
        neg = " ".join(prng.choice((NEGATIVE[it], NEGATIVE_ALT[it])).format(skill=skill) for it in neg_items)
        return positive, neg
    if style in ("blunt", "harsh"):
        pos = f"{_topic(', '.join(pos_items[:3]))} 괜찮았습니다."
        neg = " ".join(prng.choice(BLUNT[it]).format(skill=skill) for it in neg_items)
        if style == "harsh":
            neg += " " + prng.choice(BLUNT_CLOSERS)
        return pos, neg
    if style == "soft":
        neg = f"{prng.choice(SOFT_CLOSERS)} {_topic(neg_items[0])} 조금만 더 신경 쓰면 좋겠습니다."
        return positive, neg
    raise ValueError(f"모르는 글 성향: {style}")
