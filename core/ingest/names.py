"""가상 묶음의 사람 이름(사용자 요청 2026-10-11: "이름표(dp0082) 대신 실제 가상의 이름을 만들어서 데이터를 구성해줘").

흔한 성(실제 빈도에 가깝게 가중)과 흔한 두 글자 이름을 묶은 한국어 가상 이름이다. 특정인을 가리키지 않는다(유명인 이름 목록을 쓰지 않는다).
- 사람 ID마다 고정: 알려진 그룹 접두(KNOWN_PREFIXES) × 1~MAX_NUMBER 전체 이름표를 한 번에 만들어 **이름표 전체에서 중복이 없고**,
  같은 ID는 어느 묶음(100·200·300명, 연초·운영 중)에서든 같은 이름이다.
- 이름표 밖 ID(다른 접두·번호)는 예전처럼 "가상" + ID를 쓴다.
- 이름표는 이 모듈의 난수열로만 만든다 -- 묶음 생성기의 다른 표(사람 특성·이력·평가)의 난수열은 건드리지 않는다.
"""
from __future__ import annotations

import random
import re
from functools import lru_cache

KNOWN_PREFIXES = ("DP", "AI", "AU")          # core.ingest.org_profile 그룹 순서
MAX_NUMBER = 120                 # 묶음은 그룹당 100명까지 쓴다(org_profile.SIZES). 앞번호 이름은 MAX_NUMBER와 무관하다(번호 순으로 채움)
SEED = 20261011

# 성과 대략의 비중(%) -- 인구 통계의 큰 순서를 따른 근사값
SURNAMES = (("김", 21), ("이", 15), ("박", 8), ("최", 5), ("정", 4), ("강", 2.4), ("조", 2.1), ("윤", 2.1), ("장", 2), ("임", 1.7),
            ("한", 1.5), ("오", 1.5), ("서", 1.5), ("신", 1.5), ("권", 1.4), ("황", 1.4), ("안", 1.4), ("송", 1.3), ("류", 1.2),
            ("전", 1.1), ("홍", 1.1), ("고", 0.9), ("문", 0.9), ("양", 0.9), ("손", 0.9), ("배", 0.8), ("백", 0.8), ("허", 0.6),
            ("유", 0.6), ("남", 0.6), ("심", 0.5), ("노", 0.5), ("하", 0.5), ("곽", 0.4), ("성", 0.4), ("차", 0.4), ("주", 0.4),
            ("우", 0.4), ("구", 0.4), ("민", 0.3), ("진", 0.3), ("나", 0.3), ("지", 0.3), ("엄", 0.3), ("변", 0.3), ("채", 0.3))
GIVEN = ("민준", "서준", "도윤", "예준", "시우", "하준", "주원", "지호", "지후", "준우", "준서", "도현", "건우", "현우", "우진", "선우", "서진",
         "민재", "현준", "연우", "유준", "정우", "승우", "승현", "시윤", "준혁", "은우", "지환", "승민", "지우", "유찬", "윤우", "민성", "준영",
         "시후", "진우", "지원", "수현", "재윤", "시현", "동현", "태윤", "민우", "재원", "한결", "지민", "성민", "상현", "영호", "성호",
         "정훈", "동욱", "재훈", "상우", "기현", "태호", "형준", "준호", "영진", "성진", "경민", "대현", "종현", "석진", "용준", "재민",
         "서연", "서윤", "지우", "서현", "민서", "하은", "하윤", "윤서", "지유", "지민", "채원", "수아", "지아", "지윤", "다은", "은서",
         "예은", "수빈", "소율", "예린", "지안", "하린", "소윤", "유나", "민지", "예원", "채은", "가은", "윤아", "수민", "은지", "혜진",
         "지현", "미영", "은영", "현정", "지영", "수진", "미정", "선영", "유진", "주희", "보람", "아름", "혜원", "나연", "다현", "소연",
         "정민", "세영", "하늘", "은비", "효진", "슬기", "민경", "지혜", "현주", "예지", "윤정", "소희", "경은", "수정", "진주", "가영")
_ID = re.compile(r"([A-Z]+)(\d+)")


@lru_cache(maxsize=1)
def _table() -> dict[str, str]:
    rng = random.Random(SEED)
    names = [s for s, _ in SURNAMES]
    weights = [w for _, w in SURNAMES]
    given = sorted(set(GIVEN))
    # 가장 흔한 성(김 21%)이 받을 몫이 그 성의 이름 수를 넘으면 그 성이 동나 뒤쪽 번호의 성씨 분포가 평평해지고(거절 표집), 조합이 동나면 끝나지 않는다
    if max(weights) / sum(weights) * len(KNOWN_PREFIXES) * MAX_NUMBER > 0.8 * len(given):
        raise ValueError("이름표가 가장 흔한 성의 이름 수에 비해 너무 크다 -- MAX_NUMBER를 줄이거나 이름 목록을 늘린다")
    used: set[str] = set()
    out: dict[str, str] = {}
    for n in range(1, MAX_NUMBER + 1):                 # 번호 순으로 그룹을 섞어 채운다 -- 실제로 쓰는 앞번호(그룹당 100명)가 표의 앞쪽이라 성씨 분포가 자연스럽다
        for prefix in KNOWN_PREFIXES:
            while True:
                name = rng.choices(names, weights=weights)[0] + rng.choice(given)
                if name not in used:
                    break
            used.add(name)
            out[f"{prefix}{n:04d}"] = name
    return out


def virtual_name(person_id: str) -> str:
    """가상 사람 ID → 가상 이름. 이름표 밖이면 "가상" + ID."""
    m = _ID.fullmatch(person_id)
    if m and m.group(1) in KNOWN_PREFIXES:
        name = _table().get(person_id)
        if name:
            return name
    return f"가상{person_id}"
