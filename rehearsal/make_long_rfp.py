def table(code: str, title: str, items: list[str], count: int) -> str:
    rows = []
    for i in range(count):
        t = items[i % len(items)].format(n=5 + (i * 7) % 26, d=DAYS[i % 5])
        rows.append(f"요구사항 고유번호: {code}-{i + 1:03d}\n요구사항 명칭: {title} {i + 1}\n세부 내용: {t}\n")
    return "\n".join(rows)


